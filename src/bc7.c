typedef struct { const uint8_t *b; unsigned pos; } Bits;
static unsigned getb(Bits *r, unsigned n)
{
    unsigned v = 0;
    for (unsigned i = 0; i < n; i++, r->pos++)
        if (r->pos < 128) v |= (unsigned)(r->b[r->pos >> 3] >> (r->pos & 7) & 1) << i;
    return v;
}

static uint8_t interp(unsigned e0, unsigned e1, unsigned w) { return (uint8_t)(((64 - w) * e0 + w * e1 + 32) >> 6); }
static unsigned expand(unsigned v, unsigned bits) { v <<= 8 - bits; return (v | v >> bits) & 255; }

void bc7_block(const uint8_t *s, uint8_t out[16][4])
{
    int mode = 0;
    while (mode < 8 && !(s[0] >> mode & 1)) mode++;
    if (mode == 8) { memset(out, 0, 64); return; }
    const uint8_t *m = MI[mode];
    unsigned ns = m[0], cb = m[4], ab = m[5], ib = m[8], ib2 = m[9];
    Bits r = { s, (unsigned)mode + 1 };
    unsigned part = getb(&r, m[1]), rot = getb(&r, m[2]), isb = getb(&r, m[3]);
    unsigned ep[6][4];
    for (int c = 0; c < 3; c++)
        for (unsigned e = 0; e < ns * 2; e++) ep[e][c] = getb(&r, cb);
    for (unsigned e = 0; e < ns * 2; e++) ep[e][3] = ab ? getb(&r, ab) : 255;
    unsigned cbits = cb, abits = ab;
    if (m[6]) {           /* one p-bit per endpoint */
        for (unsigned e = 0; e < ns * 2; e++) {
            unsigned p = getb(&r, 1);
            for (int c = 0; c < 3; c++) ep[e][c] = ep[e][c] << 1 | p;
            if (ab) ep[e][3] = ep[e][3] << 1 | p;
        }
        cbits++; if (ab) abits++;
    } else if (m[7]) {    /* one p-bit per subset */
        for (unsigned sbs = 0; sbs < ns; sbs++) {
            unsigned p = getb(&r, 1);
            for (int k = 0; k < 2; k++) {
                for (int c = 0; c < 3; c++) ep[sbs * 2 + k][c] = ep[sbs * 2 + k][c] << 1 | p;
                if (ab) ep[sbs * 2 + k][3] = ep[sbs * 2 + k][3] << 1 | p;
            }
        }
        cbits++; if (ab) abits++;
    }
    for (unsigned e = 0; e < ns * 2; e++) {
        for (int c = 0; c < 3; c++) ep[e][c] = expand(ep[e][c], cbits);
        if (ab) ep[e][3] = expand(ep[e][3], abits);
    }
    const uint8_t *pt = ns == 2 ? P2[part] : ns == 3 ? P3[part] : NULL;
    unsigned anc[3] = { 0, ns == 2 ? A2[part] : ns == 3 ? A3a[part] : 0, ns == 3 ? A3b[part] : 0 };
    unsigned i1[16], i2[16];
    for (int p = 0; p < 16; p++) {
        unsigned sbs = pt ? pt[p] : 0, n = ib;
        if ((unsigned)p == anc[sbs]) n--;
        i1[p] = getb(&r, n);
    }
    if (ib2) for (int p = 0; p < 16; p++) i2[p] = getb(&r, p == 0 ? ib2 - 1 : ib2);
    for (int p = 0; p < 16; p++) {
        unsigned sbs = pt ? pt[p] : 0;
        const unsigned *e0 = ep[sbs * 2], *e1 = ep[sbs * 2 + 1];
        unsigned ci, ai, cb2, ab2;
        if (ib2) {
            if (isb) { ci = i2[p]; cb2 = ib2; ai = i1[p]; ab2 = ib; }
            else     { ci = i1[p]; cb2 = ib;  ai = i2[p]; ab2 = ib2; }
        } else { ci = ai = i1[p]; cb2 = ab2 = ib; }
        const uint8_t *wc = cb2 == 2 ? W2 : cb2 == 3 ? W3 : W4, *wa = ab2 == 2 ? W2 : ab2 == 3 ? W3 : W4;
        for (int c = 0; c < 3; c++) out[p][c] = interp(e0[c], e1[c], wc[ci]);
        out[p][3] = ab ? interp(e0[3], e1[3], wa[ai]) : 255;
        if (rot) { uint8_t t = out[p][3]; out[p][3] = out[p][rot - 1]; out[p][rot - 1] = t; }
    }
}
