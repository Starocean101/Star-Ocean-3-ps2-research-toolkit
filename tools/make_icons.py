#!/usr/bin/env python3
"""Cut the PS button icons out of their baked-in checkerboard backgrounds and
emit them as RGBA sprites (C header) at two sizes.

Usage: make_icons.py <cross> <circle> <triangle> <square> <out.h> [preview.png]
Glyph codes used by the app: \\x01 cross, \\x02 circle, \\x03 triangle, \\x04 square.
"""
import sys
import numpy as np
from PIL import Image, ImageDraw

SIZES = {"S": 30, "L": 44}   # small font rows are 32 px tall, large ~48


def cut_out(path):
    im = Image.open(path).convert("RGB")
    a = np.asarray(im).astype(np.int32)
    lum = (a[..., 0] * 299 + a[..., 1] * 587 + a[..., 2] * 114) // 1000
    sat = a.max(axis=2) - a.min(axis=2)
    button = (lum < 200) | (sat > 40)          # checkerboard = light and grey
    ys, xs = np.nonzero(button)
    # robust circle fit: centre = midpoint of extents, radius from the extents
    cx, cy = (xs.min() + xs.max()) / 2.0, (ys.min() + ys.max()) / 2.0
    r = min(xs.max() - xs.min(), ys.max() - ys.min()) / 2.0 - 2.0  # trim the fringe
    # anti-aliased circular mask, drawn 4x and downsampled
    ss = 4
    mask = Image.new("L", (im.width * ss, im.height * ss), 0)
    ImageDraw.Draw(mask).ellipse([(cx - r) * ss, (cy - r) * ss, (cx + r) * ss, (cy + r) * ss], fill=255)
    mask = mask.resize(im.size, Image.LANCZOS)
    rgba = im.convert("RGBA")
    rgba.putalpha(mask)
    box = (int(cx - r - 1), int(cy - r - 1), int(cx + r + 2), int(cy + r + 2))
    return rgba.crop(box)


def main():
    paths, out = sys.argv[1:5], sys.argv[5]
    names = ["cross", "circle", "triangle", "square"]
    icons = [cut_out(p) for p in paths]
    with open(out, "w") as f:
        f.write("/* Generated by tools/make_icons.py - PS button icons, RGBA. */\n#pragma once\n")
        for tag, px in SIZES.items():
            f.write(f"#define ICON_{tag} {px}\n")
            f.write(f"static const unsigned char ICON_{tag}_DATA[4][{px}][{px}][4] = {{\n")
            for name, ic in zip(names, icons):
                small = ic.resize((px, px), Image.LANCZOS)
                d = np.asarray(small)
                f.write("{ /* %s */\n" % name)
                for row in d:
                    f.write("{" + ",".join("{%d,%d,%d,%d}" % tuple(p) for p in row) + "},\n")
                f.write("},\n")
            f.write("};\n")
    if len(sys.argv) > 6:  # preview on the nebula, both sizes
        bg = Image.open("/home/claude/app2/assets/icon0.png").convert("RGBA").resize((420, 140))
        x = 10
        for ic in icons:
            for px, y in ((44, 10), (30, 80)):
                s = ic.resize((px, px), Image.LANCZOS)
                bg.alpha_composite(s, (x, y))
            x += 100
        big = bg.resize((840, 280), Image.NEAREST)
        big.save(sys.argv[6])


if __name__ == "__main__":
    main()
